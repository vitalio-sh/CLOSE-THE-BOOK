"""Mine the frozen (sign, bank-text prefix) -> category lookup from TRAIN golden.

Only TRAIN labels booked before --cutoff are read (default 2024-10-01, so the October 2024
and January 2025 evaluation windows stay held out).  A key enters the table only when it
is near-pure (>= --purity) over >= --min-count TRAIN lines and its majority is a category
that never depends on the counterparty (refund/advance categories are excluded).

usage: python3.12 scripts/mine_nonitem_lookup.py --data data/workspace [--out recon/nonitem_lookup.py]
"""
import argparse
from collections import Counter, defaultdict
from pathlib import Path
import sys

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from recon.context import read_csv  # noqa: E402
from recon.nonitem import text_key  # noqa: E402

EXCLUDED = {'ITEM', 'UNIDENTIFIED', 'CUSTOMER_REFUND', 'SUPPLIER_REFUND', 'CUSTOMER_ADVANCE'}


def main(argv=None):
    p = argparse.ArgumentParser()
    p.add_argument('--data', default='data/workspace')
    p.add_argument('--cutoff', default='2024-10-01')
    p.add_argument('--min-count', type=int, default=20)
    p.add_argument('--purity', type=float, default=0.995)
    p.add_argument('--out', default=str(Path(__file__).resolve().parents[1] / 'recon' / 'nonitem_lookup.py'))
    a = p.parse_args(argv)
    train = Path(a.data) / 'train'
    kind = {}
    for r in read_csv(train / 'golden_allocations.csv.gz'):
        kind.setdefault(r['bank_txn_id'], 'ITEM' if r['item_id'] else r['category'])
    counts = defaultdict(Counter)
    for txn in read_csv(train / 'bank_transactions.csv.gz'):
        if txn['booking_date'] >= a.cutoff or txn['bank_txn_id'] not in kind:
            continue
        counts[text_key(txn)][kind[txn['bank_txn_id']]] += 1
    table = {}
    for key, c in counts.items():
        n = sum(c.values())
        top, hits = c.most_common(1)[0]
        if n >= a.min_count and hits / n >= a.purity and top not in EXCLUDED:
            table[key] = (top, n, hits)
    lines = ['"""Generated by scripts/mine_nonitem_lookup.py from TRAIN golden booked before '
             f'{a.cutoff}.', f'min_count={a.min_count}, purity={a.purity}; value comments: TRAIN hits/lines.', '"""',
             'CATEGORY_LOOKUP = {']
    for key in sorted(table):
        top, n, hits = table[key]
        lines.append(f'    {key!r}: {top!r},  # {hits}/{n}')
    lines.append('}')
    Path(a.out).write_text('\n'.join(lines) + '\n')
    print(f'{len(table)} keys -> {a.out}')


if __name__ == '__main__':
    main()
